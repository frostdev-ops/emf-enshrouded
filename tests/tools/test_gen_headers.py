def emf_form():
    def t(i, name, ns, kind, size, h, ih, inner=None, count=0, **kw):
        d = {"index": i, "name": name, "impact_name": name, "qualified_name": "::".join(ns + [name]), "namespace": ns,
             "kind": kind, "flags": 0, "size": size, "alignment": 1, "element_alignment": 1, "hash": h,
             "internal_hash": ih, "inner": inner, "count": count}
        d.update(kw)
        return d
    return {"format": "emf-types", "format_version": 1, "source": {"file": "enshrouded.exe", "sha256": "ab" * 32},
            "type_table": {"count": 5}, "groups": {}, "types": [
                t(0, "sint64", ["keen"], "sint64", 8, 1, 2),
                t(1, "uint8", ["keen"], "uint8", 1, 3, 4),
                t(2, "Component", ["keen", "ecs"], "struct", 1, 5, 6, attributes=[["abstract", ""]]),
                t(3, "Mode", ["keen", "ecs"], "enum", 1, 7, 8, inner=1, count=2,
                  values=[{"name": "Off", "value": 0}, {"name": "On", "value": 1}]),
                t(4, "Thing", ["keen", "ecs"], "struct", 16, 0x0A0B0C0D, 9, inner=2, count=2,
                  fields=[{"name": "x", "type": 0, "offset": 0}, {"name": "mode", "type": 3, "offset": 8}]),
            ]}


class Sources(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="emf_gen_headers_")
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def gen(self, doc, name):
        out = os.path.join(self.tmp, name, "components.hpp")
        with redirect_stdout(io.StringIO()):
            gen_headers.generate(doc, out)
        return read_text(out), read_text(os.path.join(self.tmp, name, "reflection.hpp"))

    def test_eml_and_emf_forms_give_the_same_headers(self):
        eml_c, eml_r = self.gen(gen_headers.from_eml(EML), "eml")
        emf_c, emf_r = self.gen(emf_form(), "emf")
        self.assertIn("struct Thing {", emf_c)
        self.assertEqual(body(eml_c), body(emf_c))
        self.assertEqual(body(eml_r), body(emf_r))

    def test_the_first_lines_name_the_source(self):
        eml_c, eml_r = self.gen(gen_headers.from_eml(EML), "eml")
        emf_c, emf_r = self.gen(emf_form(), "emf")
        self.assertTrue(eml_c.startswith("// GENERATED by tools/gen_headers.py from EML types.json. Do not edit.\n"
                                         "// Source version: 1|test\n"))
        self.assertTrue(emf_c.startswith("// GENERATED by tools/gen_headers.py from the game's reflection data "
                                         "(tools/re/exe_types.py). Do not edit.\n// Source: enshrouded.exe, sha256 "))
        self.assertTrue(emf_r.startswith("// GENERATED by tools/gen_headers.py from the game's reflection data"))

    def test_a_component_derives_from_keen_ecs_component_found_by_name(self):
        c, r = self.gen(emf_form(), "emf")
        self.assertIn('{"keen::ecs::Thing", 0x0a0b0c0du, 16},', c)
        self.assertIn("static_assert(offsetof(emf::gen::ecs::Thing, mode) == 8);", c)
        self.assertIn("enum class Mode : uint8_t {", c)

    def test_load_reads_each_kind_of_source(self):
        eml_path = os.path.join(self.tmp, "types.json")
        emf_path = os.path.join(self.tmp, "types.emf.json")
        with open(eml_path, "w", encoding="utf-8") as f:
            json.dump(EML, f)
        exe_types.write_types(emf_form(), emf_path)
        self.assertEqual(gen_headers.load(eml_path)["format"], "eml-types")
        self.assertEqual(gen_headers.load(emf_path)["format"], "emf-types")
        b, t, order = fx.small_game()
        exe = os.path.join(self.tmp, "enshrouded.exe")
        with open(exe, "wb") as f:
            f.write(b.pe_bytes())
        doc = gen_headers.load(exe)
        self.assertEqual(doc["format"], "emf-types")
        self.assertEqual(doc["source"]["file"], "enshrouded.exe")

    def test_headers_from_an_exe(self):
        b, t, order = fx.small_game()
        exe = os.path.join(self.tmp, "enshrouded.exe")
        with open(exe, "wb") as f:
            f.write(b.pe_bytes())
        out = os.path.join(self.tmp, "exe", "components.hpp")
        with redirect_stdout(io.StringIO()):
            gen_headers.main([exe, out])
        c = read_text(out)
        self.assertIn("struct Health {", c)
        self.assertIn("static_assert(offsetof(emf::gen::ecs::Health, faction) == 4);", c)
        self.assertIn("static_assert(sizeof(emf::gen::ecs::Position) == 24);", c)
        self.assertIn('{"keen::ecs::Health", 0x5eed0005u, 12},', c)
        self.assertIn('{"keen::ecs::Position", 0x0a0b0c0du, 24},', c)
        self.assertNotIn('{"keen::ecs::Component"', c)  # abstract


class RefusesToWriteEmptyHeaders(unittest.TestCase):
    """With the default output these would overwrite the SDK's headers: nothing is written, the run stops."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="emf_gen_headers_")
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.out = os.path.join(self.tmp, "gen", "components.hpp")

    def refused(self, doc):
        with redirect_stdout(io.StringIO()), self.assertRaises(SystemExit) as e:
            gen_headers.generate(doc, self.out)
        self.assertFalse(os.path.exists(os.path.dirname(self.out)))
        return str(e.exception.code)

    def test_without_keen_ecs_component(self):
        doc = emf_form()
        doc["types"] = [t for t in doc["types"] if t["qualified_name"] != "keen::ecs::Component"]
        doc["types"][-1]["inner"] = None
        self.assertIn("keen::ecs::Component", self.refused(doc))

    def test_without_any_component(self):
        doc = emf_form()
        doc["types"] = [t for t in doc["types"] if t["qualified_name"] != "keen::ecs::Thing"]
        self.assertIn("no components", self.refused(doc))


class BadSources(unittest.TestCase):
    """A wrong path or a broken file ends with one line saying what is wrong, not a traceback."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="emf_gen_headers_")
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def write(self, name, data):
        path = os.path.join(self.tmp, name)
        with open(path, "wb") as f:
            f.write(data)
        return path

    def says(self, path):
        with self.assertRaises(SystemExit) as e:
            gen_headers.load(path)
        msg = str(e.exception.code)
        self.assertIn("gen_headers.py", msg)
        self.assertNotIn("\n", msg.strip())
        return msg

    def test_a_missing_file(self):
        self.assertIn("nothing.exe", self.says(os.path.join(self.tmp, "nothing.exe")))

    def test_emf_game_dir_without_the_exe(self):
        """A dedicated server folder holds enshrouded_server.exe, not enshrouded.exe."""
        from unittest import mock
        with mock.patch.dict(os.environ, {"EMF_GAME_DIR": self.tmp}), self.assertRaises(SystemExit) as e:
            gen_headers.main([])
        self.assertIn("enshrouded.exe", str(e.exception.code))

    def test_broken_json(self):
        self.says(self.write("types.json", b"{not json"))

    def test_json_without_types(self):
        self.says(self.write("types.json", b'{"version": "1"}'))

    def test_a_cut_off_exe(self):
        b, t, order = fx.small_game()
        self.says(self.write("enshrouded.exe", b.pe_bytes()[:0x300]))

    def test_an_exe_without_the_registry_root(self):
        b = fx.ImageBuilder()
        keen = b.namespace("keen")
        types = [b.type("keen::T%d" % i, "uint32", size=4, align=4, namespace=keen, hash=0x5EED0100 + i)
                 for i in range(3)]
        b.holder(b.pointers(types), 3)
        self.assertIn("root", self.says(self.write("enshrouded.exe", b.pe_bytes())))


def game_exe_of_the_headers():
    """EMF_GAME_DIR's enshrouded.exe when it is the build the committed headers were made from, else None."""
    game = os.environ.get("EMF_GAME_DIR")
    if not game:
        return None
    exe = os.path.join(game, "enshrouded.exe")
    if not os.path.isfile(exe):
        return None
    m = re.search(r"sha256 ([0-9a-f]{64})", read_text(os.path.join(GENERATED, "components.hpp")))
    if not m:
        return None
    with open(exe, "rb") as f:
        return exe if hashlib.sha256(f.read()).hexdigest() == m.group(1) else None


@unittest.skipUnless(game_exe_of_the_headers(), "needs EMF_GAME_DIR with the exe the headers were generated from")
class CommittedHeaders(unittest.TestCase):
    def test_regenerated_from_the_game_exe_they_are_unchanged(self):
        tmp = tempfile.mkdtemp(prefix="emf_gen_headers_")
        self.addCleanup(shutil.rmtree, tmp, True)
        out = os.path.join(tmp, "components.hpp")
        with redirect_stdout(io.StringIO()):
            gen_headers.main([game_exe_of_the_headers(), out])
        for name in ("components.hpp", "reflection.hpp"):
            self.assertEqual(read_text(os.path.join(tmp, name)), read_text(os.path.join(GENERATED, name)), name)


